s32 s_sjisForAscii;
ParseStringFn s_parseString;

static u8* ParseStringNarrow(s32 encode, u8* str, OSFontHeader** font, s32* code);
static u8* ParseStringWide(s32 encode, u8* str, OSFontHeader** font, s32* code);

static inline BOOL IsSjisLeadByte(u8 c) {
    return (c >= 0x81 && c <= 0x9F) || (c >= 0xE0 && c <= 0xFC);
}

static inline BOOL IsSjisTrailByte(u8 c) {
    return c >= 0x40 && 0xFC >= c && c != 0x7F;
}

static inline u16 GetFontEncode(void) {
    u32 enc = s_fontEncode;

    if (enc != 0xFFFF) {
        return enc;
    }
    if (*(s32*)0x800000CC == 0) {
        enc = (*(u16*)0xCC00206E >> 1) & 1;
        s_fontEncode = enc;
    } else {
        enc = 0;
        s_fontEncode = 0;
    }
    s_parseString = ParseStringNarrow;
    return enc;
}

/* 0x804CFF80 (0x138): maps a character code of the given font encoding to its glyph cell index; 0 when it has none. */
static u32 GetFontCode(u32 encode, u16 code) {
    if (encode == 1) {
        if (code >= 0x20 && 0xDF >= code) {
            return sjisSingleCode[code - 0x20];
        }
        if (code > 0x889E && 0x9872 >= code) {
            s32 row = ((code >> 8) - 0x88) * 188;
            s32 col = code & 0xFF;
            if (!IsSjisTrailByte(col)) {
                return 0;
            }
            col -= 0x40;
            if (col >= 0x40) {
                col--;
            }
            return row + col + 702;
        }
        if (code >= 0x8140 && 0x879E > code) {
            s32 row = ((code >> 8) - 0x81) * 188;
            s32 col = code & 0xFF;
            if (!IsSjisTrailByte(col)) {
                return 0;
            }
            col -= 0x40;
            if (col >= 0x40) {
                col--;
            }
            return sjisDoubleCode[row + col];
        }
    } else if ((u16)(code + 0xFFDF) <= 222) {
        return code - 32;
    }
    return 0;
}

/* 0x804D00C0 (0x1A8): expands a Yay0 image into `dst`. */
static void DecodeYay0(Yay0Header* src, u8* dst) {
    u8* srcBytes = (u8*)src;
    u8* chunk = srcBytes + src->chunkOffset;
    s32 size = src->expandedSize;
    u32* codes = src->flagWords;
    s32 outPos = 0;
    s32 linkOffset = src->linkOffset;
    s32 bitsLeft = 0;
    u32 bits;

    do {
        if (bitsLeft == 0) {
            bits = *codes++;
            bitsLeft = 32;
        }
        if (bits & 0x80000000) {
            dst[outPos++] = *chunk++;
        } else {
            s32 link = (srcBytes[linkOffset] << 8) | srcBytes[linkOffset + 1];
            s32 count = link >> 12;
            s32 from = outPos - (link & 0xFFF);
            s32 i;
            linkOffset += 2;
            if (count == 0) {
                count = *chunk++ + 18;
            } else {
                count += 2;
            }
            for (i = 0; i < count; i++, outPos++, from++) {
                dst[outPos] = dst[from - 1];
            }
        }
        bits <<= 1;
        bitsLeft--;
    } while (outPos < size);
}

/* 0x804D0270 (0x78): selects the string encoding of the font and returns the previous one. */
u16 OSSetFontEncode(u16 encode) {
    u16 prev = GetFontEncode();

    if (encode <= 5) {
        s_fontEncode = encode;
        if (encode >= 3 && 5 >= encode) {
            s_parseString = ParseStringWide;
        }
    }
    return prev;
}

static inline void ReadRom(u8* buf, s32 length, s32 offset) {
    s32 n;
    for (; length > 0; length -= n, offset += n, buf += n) {
        n = length > 256 ? 256 : length;
        while (!__OSReadROM(buf, n, offset)) {
        }
    }
}

/* Row address of the texel (x, y) in a 2-bit 8x8-tiled font sheet. */
static inline u8* SheetRow(OSFontHeader* font, u8* sheet, s32 x, s32 y) {
    return sheet + (y / 8) * (font->sheetWidth / 8 * 32 / 2) + (x / 8) * 16 + (y % 8) * 2 + (x % 8) / 4;
}

/* 0x804D02F0 (0x310): reads the ROM font of `encode` into `src`, expands it into `dst` and returns the expanded size. */
static u32 ReadFont(u8* src, u16 encode, OSFontHeader* dst) {
    u32 size;

    if (encode == 1) {
        ReadRom(src, 0x4D000, 0x1AFF00);
    } else {
        ReadRom(src, 0x3000, 0x1FCF00);
    }
    if (src[0] == 'Y' && src[1] == 'a' && src[2] == 'y') {
        size = ((Yay0Header*)src)->expandedSize;
    } else {
        size = 0;
    }
    if (size == 0) {
        return 0;
    }
    DecodeYay0((Yay0Header*)src, (u8*)dst);
    if (encode == 1) {
        u16 rows[4] = {0x2ABE, 0x003D, 0x003D, 0x003D};
        s32 index;
        s32 sheetIndex;
        s32 inSheet;
        s32 cellRow;
        s32 cellCol;
        s32 x;
        s32 y;
        u8* sheet;

        index = GetFontCode(encode, 0x54);
        sheetIndex = index / (dst->sheetColumn * dst->sheetRow);
        inSheet = index % (dst->sheetColumn * dst->sheetRow);
        cellRow = inSheet / dst->sheetColumn;
        cellCol = inSheet % dst->sheetColumn;
        y = cellRow * dst->cellHeight;
        x = cellCol * dst->cellWidth;
        sheet = (u8*)dst + dst->sheetImage + ((u32)(sheetIndex * dst->sheetSize) >> 1);
        *(u16*)SheetRow(dst, sheet, x, y + 4) = rows[0];
        *(u16*)SheetRow(dst, sheet, x, y + 5) = rows[1];
        *(u16*)SheetRow(dst, sheet, x, y + 6) = rows[2];
        *(u16*)SheetRow(dst, sheet, x, y + 7) = rows[3];
    }
    return size;
}

/* 0x804D0600 (0x118): reads the ROM fonts into `dst` (using `work` as the compressed buffer) and returns the bytes used. */
u32 OSInitFont(OSFontHeader* dst, u8* work) {
    u32 size;
    u16 encode = GetFontEncode();

    switch (encode) {
    case 0:
        s_ansiFont = dst;
        size = ReadFont(work, 0, dst);
        break;
    case 1:
        s_sjisFont = dst;
        size = ReadFont(work, 1, dst);
        break;
    case 3:
    case 4:
    case 5:
        s_ansiFont = dst;
        size = ReadFont(work, 0, dst);
        if (size != 0) {
            s_sjisFont = (OSFontHeader*)((u8*)s_ansiFont + size);
            size += ReadFont(work, 1, s_sjisFont);
        }
        break;
    default:
        size = 0;
        break;
    }
    return size;
}

/* 0x804D0720 (0xF8): reads one single- or double-byte character and returns the position after it. */
static u8* ParseStringNarrow(s32 encode, u8* str, OSFontHeader** font, s32* code) {
    OSFontHeader* sel;
    u16 ch = 0;

    switch (encode) {
    case 0:
        ch = *str;
        sel = s_ansiFont;
        if (ch != 0) {
            str++;
        }
        break;
    case 1:
        ch = *str;
        sel = s_sjisFont;
        if (ch != 0) {
            str++;
            if (IsSjisLeadByte(ch) && IsSjisTrailByte(*str)) {
                ch = (ch << 8) | *str++;
            }
        }
        break;
    }
    *font = sel;
    *code = GetFontCode(encode, ch);
    return str;
}

/* 0x804D0820 (0x1B4): reads one character of any supported string encoding and returns the position after it. */
static u8* ParseStringWide(s32 encode, u8* str, OSFontHeader** font, s32* code) {
    OSFontHeader* sel;
    u16 ch = 0;
    u32 point = 0;

    switch (encode) {
    case 0:
        ch = *str;
        sel = s_ansiFont;
        if (ch != 0) {
            str++;
        }
        break;
    case 1:
        ch = *str;
        sel = s_sjisFont;
        if (ch != 0) {
            str++;
            if (IsSjisLeadByte(ch) && IsSjisTrailByte(*str)) {
                ch = (ch << 8) | *str++;
            }
        }
        break;
    case 3:
        str = OSUTF8to32(str, &point);
        break;
    case 4:
        str = (u8*)OSUTF16to32((u16*)str, &point);
        break;
    case 5:
        point = *(u32*)str;
        if (point != 0) {
            str += 4;
        }
        break;
    }
    if (point != 0) {
        sel = s_ansiFont;
        encode = 0;
        ch = OSUTF32toANSI(point);
        if (ch == 0 || (s_sjisForAscii != 0 && point <= 0x7F)) {
            ch = OSUTF32toSJIS(point);
            if (ch != 0) {
                encode = 1;
                sel = s_sjisFont;
            }
        }
    }
    *font = sel;
    *code = GetFontCode(encode, ch);
    return str;
}

/* 0x804D09E0 (0x288): renders the glyph of the first character of `string` into the 4-bit texture `image` at column `pos`. */
char* OSGetFontTexel(const char* string, u8* image, s32 pos, s32 stride, s32* width) {
    OSFontHeader* font;
    s32 code;
    s32 sheetIndex;
    s32 inSheet;
    s32 cellRow;
    s32 cellCol;
    s32 srcX0;
    s32 srcY0;
    s32 cy;
    s32 cx;
    u8* sheet;
    u32 encode = GetFontEncode();

    u8* next = s_parseString(encode, (u8*)string, &font, &code);
    sheetIndex = code / (font->sheetColumn * font->sheetRow);
    inSheet = code % (font->sheetColumn * font->sheetRow);
    cellRow = inSheet / font->sheetColumn;
    cellCol = inSheet % font->sheetColumn;
    srcY0 = cellRow * font->cellHeight;
    srcX0 = cellCol * font->cellWidth;
    sheet = (u8*)font + font->sheetImage + ((u32)(sheetIndex * font->sheetSize) >> 1);
    for (cy = 0; cy < font->cellHeight; cy++) {
        for (cx = 0; cx < font->cellWidth; cx++) {
            s32 dx = pos + cx;
            u8 texel = *SheetRow(font, sheet, srcX0 + cx, srcY0 + cy);
            u8* out = image + (cy / 8) * ((stride * 4 / 8) << 5) + (dx / 8) * 32 + (cy % 8) * 4 + (dx % 8) / 2;
            s32 mask = 0xF0;
            if (dx % 2 != 0) {
                mask = 0x0F;
            }
            *out |= (u8)(font->c[(texel >> (6 - (srcX0 + cx) % 4 * 2)) & 3] & mask);
        }
    }
    if (width != NULL) {
        *width = *((u8*)font + font->widthTable + code);
    }
    return (char*)next;
}
