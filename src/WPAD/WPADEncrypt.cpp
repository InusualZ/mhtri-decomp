/* Rotates the byte `value` left by `shift` bits. */
static inline u8 wpadRol8(u8 value, u8 shift)
{
    return (value << shift) | (value >> (8 - shift));
}

/* Rotates the byte `value` right by `shift` bits. */
static inline u8 wpadRor8(u8 value, u8 shift)
{
    return (value >> shift) | (value << (8 - shift));
}

/* Builds the channel's extension key: ten random bytes, the six key bytes derived from them and the answer row, and
 * the two eight-byte decryption tables. */
void WPADiCreateKey(s32 chan)
{
    WPADCB* cb = wpadCBTable[chan];
    u8 rand[10];
    u8 key[6];
    u8 ft[8];
    u8 sb[8];
    u8 ansOffset;
    u8 idx;
    u8 i;
    u32 level;

    wpadRandSeed = OSGetTick() >> 8;
    wpadRandMultiplier = (OSGetTick() >> 16) & 0x3F;
    wpadRandIncrement = (OSGetTick() >> 24) & 0x4C;
    wpadRandModulus = 0xFF;
    wpadRandSeed = (u32)(wpadRandIncrement + wpadRandSeed * wpadRandMultiplier) % wpadRandModulus;
    idx = wpadRandSeed % 7;
    ansOffset = idx * 6;
    for (i = 0; i < 10; i++) {
        wpadRandSeed = (u32)(wpadRandIncrement + wpadRandSeed * wpadRandMultiplier) % wpadRandModulus;
        rand[i] = wpadKeySBox[wpadRandSeed];
    }
    WPADiDebugPrint("ans : %d %d %d %d %d %d\n", wpadKeyAnsTable[ansOffset + 0], wpadKeyAnsTable[ansOffset + 1],
                    wpadKeyAnsTable[ansOffset + 2], wpadKeyAnsTable[ansOffset + 3], wpadKeyAnsTable[ansOffset + 4],
                    wpadKeyAnsTable[ansOffset + 5]);
    WPADiDebugPrint("rand: %d %d %d %d %d %d %d %d %d %d\n", rand[0], rand[1], rand[2], rand[3], rand[4], rand[5],
                    rand[6], rand[7], rand[8], rand[9]);
    WPADiDebugPrint("t0  : %d %d %d %d %d %d %d %d %d %d\n", wpadKeySBox[rand[0]], wpadKeySBox[rand[1]],
                    wpadKeySBox[rand[2]], wpadKeySBox[rand[3]], wpadKeySBox[rand[4]], wpadKeySBox[rand[5]],
                    wpadKeySBox[rand[6]], wpadKeySBox[rand[7]], wpadKeySBox[rand[8]], wpadKeySBox[rand[9]]);
    level = OSDisableInterrupts();
    key[0] = (wpadRor8(wpadKeyAnsTable[ansOffset + 0] ^ wpadKeySBox[rand[5]], wpadKeySBox[rand[2]] % 8)
              - wpadKeySBox[rand[9]]) ^ wpadKeySBox[rand[4]];
    key[1] = (wpadRor8(wpadKeyAnsTable[ansOffset + 1] ^ wpadKeySBox[rand[1]], wpadKeySBox[rand[0]] % 8)
              - wpadKeySBox[rand[5]]) ^ wpadKeySBox[rand[7]];
    key[2] = (wpadRor8(wpadKeyAnsTable[ansOffset + 2] ^ wpadKeySBox[rand[6]], wpadKeySBox[rand[8]] % 8)
              - wpadKeySBox[rand[2]]) ^ wpadKeySBox[rand[8]];
    key[3] = (wpadRor8(wpadKeyAnsTable[ansOffset + 3] ^ wpadKeySBox[rand[4]], wpadKeySBox[rand[7]] % 8)
              - wpadKeySBox[rand[3]]) ^ wpadKeySBox[rand[2]];
    key[4] = (wpadRor8(wpadKeyAnsTable[ansOffset + 4] ^ wpadKeySBox[rand[1]], wpadKeySBox[rand[6]] % 8)
              - wpadKeySBox[rand[0]]) ^ wpadKeySBox[rand[3]];
    key[5] = (wpadRor8(wpadKeyAnsTable[ansOffset + 5] ^ wpadKeySBox[rand[7]], wpadKeySBox[rand[8]] % 8)
              - wpadKeySBox[rand[5]]) ^ wpadKeySBox[rand[9]];
    WPADiDebugPrint("key : %d %d %d %d %d %d \n", key[0], key[1], key[2], key[3], key[4], key[5]);
    ft[0] = wpadKeySBox[(idx + 1) * 0x100 + key[4]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[3]];
    ft[1] = wpadKeySBox[(idx + 1) * 0x100 + key[2]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[5]];
    ft[2] = wpadKeySBox[(idx + 1) * 0x100 + key[5]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[7]];
    ft[3] = wpadKeySBox[(idx + 1) * 0x100 + key[0]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[2]];
    ft[4] = wpadKeySBox[(idx + 1) * 0x100 + key[1]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[4]];
    ft[5] = wpadKeySBox[(idx + 1) * 0x100 + key[3]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[9]];
    ft[6] = wpadKeySBox[(idx + 1) * 0x100 + rand[0]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[6]];
    ft[7] = wpadKeySBox[(idx + 1) * 0x100 + rand[1]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[8]];
    sb[0] = wpadKeySBox[(idx + 1) * 0x100 + key[0]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[1]];
    sb[1] = wpadKeySBox[(idx + 1) * 0x100 + key[5]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[4]];
    sb[2] = wpadKeySBox[(idx + 1) * 0x100 + key[3]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[0]];
    sb[3] = wpadKeySBox[(idx + 1) * 0x100 + key[2]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[9]];
    sb[4] = wpadKeySBox[(idx + 1) * 0x100 + key[4]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[7]];
    sb[5] = wpadKeySBox[(idx + 1) * 0x100 + key[1]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[8]];
    sb[6] = wpadKeySBox[(idx + 1) * 0x100 + rand[3]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[5]];
    sb[7] = wpadKeySBox[(idx + 1) * 0x100 + rand[2]] ^ wpadKeySBox[(idx + 2) * 0x100 + rand[6]];
    WPADiDebugPrint("ft  : %d %d %d %d %d %d %d %d\n", ft[0], ft[1], ft[2], ft[3], ft[4], ft[5], ft[6], ft[7]);
    WPADiDebugPrint("sb  : %d %d %d %d %d %d %d %d\n", sb[0], sb[1], sb[2], sb[3], sb[4], sb[5], sb[6], sb[7]);
    for (i = 0; i < 10; i++) {
        cb->key[i] = rand[9 - i];
    }
    for (i = 0; i < 6; i++) {
        cb->key[10 + i] = key[5 - i];
    }
    memcpy(cb->keyAdd, ft, 8);
    memcpy(cb->keyXor, sb, 8);
    OSRestoreInterrupts(level);
}

/* Builds the extension key of a third-party extension: ten random bytes, the six key bytes derived from them and the
 * answer row, and the two eight-byte decryption tables. */
void WPADiCreateKeyFor3rd(s32 chan)
{
    WPADCB* cb = wpadCBTable[chan];
    u8 rand[10];
    u8 key[6];
    u8 ft[8];
    u8 sb[8];
    u8 ansOffset;
    u8 idx;
    u8 i;
    u32 level;

    wpadRandSeed = OSGetTick() >> 8;
    wpadRandMultiplier = (OSGetTick() >> 16) & 0x3F;
    wpadRandIncrement = (OSGetTick() >> 24) & 0x4C;
    wpadRandModulus = 0xFF;
    wpadRandSeed = (u32)(wpadRandIncrement + wpadRandSeed * wpadRandMultiplier) % wpadRandModulus;
    idx = wpadRandSeed % 7;
    ansOffset = idx * 6;
    for (i = 0; i < 10; i++) {
        wpadRandSeed = (u32)(wpadRandIncrement + wpadRandSeed * wpadRandMultiplier) % wpadRandModulus;
        rand[i] = wpadKey3rdSBox[wpadRandSeed];
    }
    WPADiDebugPrint("ans : %d %d %d %d %d %d\n", wpadKey3rdAnsTable[ansOffset + 0], wpadKey3rdAnsTable[ansOffset + 1],
                    wpadKey3rdAnsTable[ansOffset + 2], wpadKey3rdAnsTable[ansOffset + 3],
                    wpadKey3rdAnsTable[ansOffset + 4], wpadKey3rdAnsTable[ansOffset + 5]);
    WPADiDebugPrint("rand: %d %d %d %d %d %d %d %d %d %d\n", rand[0], rand[1], rand[2], rand[3], rand[4], rand[5],
                    rand[6], rand[7], rand[8], rand[9]);
    WPADiDebugPrint("t0  : %d %d %d %d %d %d %d %d %d %d\n", wpadKey3rdSBox[rand[0]], wpadKey3rdSBox[rand[1]],
                    wpadKey3rdSBox[rand[2]], wpadKey3rdSBox[rand[3]], wpadKey3rdSBox[rand[4]], wpadKey3rdSBox[rand[5]],
                    wpadKey3rdSBox[rand[6]], wpadKey3rdSBox[rand[7]], wpadKey3rdSBox[rand[8]], wpadKey3rdSBox[rand[9]]);
    level = OSDisableInterrupts();
    key[0] = (wpadRol8(wpadKey3rdAnsTable[ansOffset + 0] ^ wpadKey3rdSBox[rand[0]], wpadKey3rdSBox[rand[1]] % 8)
              + wpadKey3rdSBox[rand[6]]) ^ wpadKey3rdSBox[rand[7]];
    key[1] = (wpadRol8(wpadKey3rdAnsTable[ansOffset + 1] ^ wpadKey3rdSBox[rand[4]], wpadKey3rdSBox[rand[2]] % 8)
              + wpadKey3rdSBox[rand[3]]) ^ wpadKey3rdSBox[rand[1]];
    key[2] = (wpadRol8(wpadKey3rdAnsTable[ansOffset + 2] ^ wpadKey3rdSBox[rand[2]], wpadKey3rdSBox[rand[8]] % 8)
              + wpadKey3rdSBox[rand[4]]) ^ wpadKey3rdSBox[rand[5]];
    key[3] = (wpadRol8(wpadKey3rdAnsTable[ansOffset + 3] ^ wpadKey3rdSBox[rand[6]], wpadKey3rdSBox[rand[9]] % 8)
              + wpadKey3rdSBox[rand[7]]) ^ wpadKey3rdSBox[rand[0]];
    key[4] = (wpadRol8(wpadKey3rdAnsTable[ansOffset + 4] ^ wpadKey3rdSBox[rand[5]], wpadKey3rdSBox[rand[4]] % 8)
              + wpadKey3rdSBox[rand[8]]) ^ wpadKey3rdSBox[rand[1]];
    key[5] = (wpadRol8(wpadKey3rdAnsTable[ansOffset + 5] ^ wpadKey3rdSBox[rand[9]], wpadKey3rdSBox[rand[3]] % 8)
              + wpadKey3rdSBox[rand[8]]) ^ wpadKey3rdSBox[rand[5]];
    WPADiDebugPrint("key : %d %d %d %d %d %d \n", key[0], key[1], key[2], key[3], key[4], key[5]);
    ft[0] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[4]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[3]];
    ft[1] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[2]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[5]];
    ft[2] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[5]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[7]];
    ft[3] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[0]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[2]];
    ft[4] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[1]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[4]];
    ft[5] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[3]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[9]];
    ft[6] = wpadKey3rdSBox[(idx + 1) * 0x100 + rand[0]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[6]];
    ft[7] = wpadKey3rdSBox[(idx + 1) * 0x100 + rand[1]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[8]];
    sb[0] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[0]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[1]];
    sb[1] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[5]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[4]];
    sb[2] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[3]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[0]];
    sb[3] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[2]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[9]];
    sb[4] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[4]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[7]];
    sb[5] = wpadKey3rdSBox[(idx + 1) * 0x100 + key[1]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[8]];
    sb[6] = wpadKey3rdSBox[(idx + 1) * 0x100 + rand[3]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[5]];
    sb[7] = wpadKey3rdSBox[(idx + 1) * 0x100 + rand[2]] ^ wpadKey3rdSBox[(idx + 2) * 0x100 + rand[6]];
    WPADiDebugPrint("ft  : %d %d %d %d %d %d %d %d\n", ft[0], ft[1], ft[2], ft[3], ft[4], ft[5], ft[6], ft[7]);
    WPADiDebugPrint("sb  : %d %d %d %d %d %d %d %d\n", sb[0], sb[1], sb[2], sb[3], sb[4], sb[5], sb[6], sb[7]);
    for (i = 0; i < 10; i++) {
        cb->key[i] = rand[9 - i];
    }
    for (i = 0; i < 6; i++) {
        cb->key[10 + i] = key[5 - i];
    }
    memcpy(cb->keyAdd, ft, 8);
    memcpy(cb->keyXor, sb, 8);
    OSRestoreInterrupts(level);
}


/* Decrypts `length` bytes of extension data in place with the channel's key tables; `offset` is the position within the register block. */
void wpadDecryptExtension(s32 chan, u8* data, u16 length, s32 offset)
{
    WPADCB* cb = wpadCBTable[chan];
    u16 i;

    for (i = 0; i < length; i++) {
        u8 index = (offset + i) % 8;
        data[i] = (u8)(data[i] ^ cb->keyXor[index]) + cb->keyAdd[index];
    }
}
