/* homebutton/hkb_qwerty_keys.cpp - the software keyboard's QWERTY key maps: the P_key_* pane names and the eight
 *   per-language maps of 50 keys (pane name and the four wide characters a key types), whose name pointers the
 *   static initialiser 0x8055FD58 copies in.
 * RANGE. .text 0x8055FD58-0x8056083C (1 function); .ctors 0x8056F420-0x8056F424; .data 0x80655BD8-0x80657210.
 *   Edges: the key maps are read only through homebutton/hkb_keyboard.cpp's .rodata pointer tables 0x8057A690 and
 *   0x8057A730; in `.data` order they sit between this unit's records and homebutton/hbm_kb_event.cpp's first
 *   object (0x80657210), so they close this unit's claim.
 * FLAGS. GC/3.0a5.2 + cflags_hkb, the band's flags (evidence: src/homebutton/hbm_kb_event.cpp FLAGS).
 * NAMES. GUESS: the file name, from the P_key_* strings and the key maps; GUESS hkb_qwerty_key_names, HkbQwertyKey
 *   and the map names, from their contents (map 0 types the Japanese long vowel mark and brackets, map 3 is AZERTY,
 *   map 4 QWERTZ; the order follows the Wii's languages with US and UK English); the static initialiser is the
 *   compiler's __sinit_\hkb_qwerty_keys_cpp.
 * SHAPES. The maps copy their pane names from hkb_qwerty_key_names at run time (a non-const array read in an
 *   aggregate initialiser); the wide characters stay static .data.
 */
