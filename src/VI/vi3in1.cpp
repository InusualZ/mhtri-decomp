/* Sends one gamma curve to the encoder (register 0x10, 34 bytes). */
#pragma scheduling off
void __VISetGammaCoef(const VIGammaEntry* gamma)
{
    u8 data[34];

    data[0] = 0x10;
    data[2] = gamma->low[0];
    data[1] = gamma->low[0] >> 8 & 0xFF;
    data[4] = gamma->low[1];
    data[3] = gamma->low[1] >> 8 & 0xFF;
    data[6] = gamma->low[2];
    data[5] = gamma->low[2] >> 8 & 0xFF;
    data[8] = gamma->low[3];
    data[7] = gamma->low[3] >> 8 & 0xFF;
    data[10] = gamma->low[4];
    data[9] = gamma->low[4] >> 8 & 0xFF;
    data[12] = gamma->low[5];
    data[11] = gamma->low[5] >> 8 & 0xFF;
    data[13] = gamma->mid[0];
    data[14] = gamma->mid[1];
    data[15] = gamma->mid[2];
    data[16] = gamma->mid[3];
    data[17] = gamma->mid[4];
    data[18] = gamma->mid[5];
    data[19] = gamma->mid[6];
    {
        u16 v = gamma->high[0];
        u8 hi = v >> 8 & 0xFF;
        u8 lo = v & 0xC0;
        data[20] = hi;
        data[21] = lo;
    }
    {
        u16 v = gamma->high[1];
        u8 hi = v >> 8 & 0xFF;
        u8 lo = v & 0xC0;
        data[22] = hi;
        data[23] = lo;
    }
    {
        u16 v = gamma->high[2];
        u8 hi = v >> 8 & 0xFF;
        u8 lo = v & 0xC0;
        data[24] = hi;
        data[25] = lo;
    }
    {
        u16 v = gamma->high[3];
        u8 hi = v >> 8 & 0xFF;
        u8 lo = v & 0xC0;
        data[26] = hi;
        data[27] = lo;
    }
    {
        u16 v = gamma->high[4];
        u8 hi = v >> 8 & 0xFF;
        u8 lo = v & 0xC0;
        data[28] = hi;
        data[29] = lo;
    }
    {
        u16 v = gamma->high[5];
        u8 hi = v >> 8 & 0xFF;
        u8 lo = v & 0xC0;
        data[30] = hi;
        data[31] = lo;
    }
    {
        u16 v = gamma->high[6];
        u8 hi = v >> 8 & 0xFF;
        u8 lo = v & 0xC0;
        data[32] = hi;
        data[33] = lo;
    }
    __VISendI2CData(VI_ENCODER_ADDR, data, 34);
    WaitMicroTime(2);
}

