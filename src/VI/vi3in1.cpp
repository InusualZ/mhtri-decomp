{
    __VISetGammaCoef(&viEncoderTables.gamma[viGammaIndex]);
}

void __VISetTrapFilter(void)
{
    u8 data[2];

    data[0] = 3;
    if (viTrapFilter == 1) {
        data[1] = 0;
    } else {
        data[1] = 1;
    }
    __VISendI2CData(VI_ENCODER_ADDR, data, 2);
    WaitMicroTime(2);
}

void VISetTrapFilter(u8 filter)
{
    if (viTrapFilter != filter) {
        viTrapFilter = filter;
        viEncoderDirtyFlags |= 0x20;
    }
}

void __VISendEncoderReg0A(void)
{
    u8 data[2];

    if (viEncoderMode == 3) {
        data[0] = 10;
        data[1] = (viEncoderGain << 1) | 1;
        __VISendI2CData(VI_ENCODER_ADDR, data, 2);
        WaitMicroTime(2);
    } else {
        data[0] = 10;
        data[1] = 0;
        __VISendI2CData(VI_ENCODER_ADDR, data, 2);
        WaitMicroTime(2);
    }
}

void __VIRequestEncoderUpdate(void)
{
    viEncoderDirtyFlags |= 0x80;
}

void __VISetRGBModeImm(void)
{
    u8 data[2];

    viEncoderMode = 3;
    data[0] = 1;
    data[1] = 3;
    __VISendI2CData(VI_ENCODER_ADDR, data, 2);
    WaitMicroTime(2);
}

/* Programs the encoder with its power-on register sequence and the stored CGMS, WSS, closed caption and gamma settings. */
void __VIInitEncoder(void)
{
    viWriteReg(0x6A, 1);
    viWriteReg(0x65, 1);
    __VISetEncoderMode(VIGetDTVStatus());
    viWriteReg(0, 0);
    {
        u8 regs[3];

        regs[0] = 0x71;
        regs[1] = 0x8E;
        regs[2] = 0x8E;
        __VISendI2CData(VI_ENCODER_ADDR, regs, 3);
        WaitMicroTime(2);
    }
    viWriteReg(2, 7);
    viCgms0 = 0;
    viCgms1 = 0;
    viCgms2 = 0;
    __VISetCGMS();
    if (viWss0 != 0 || viWss1 != 0 || viWss2 != 0 || viWss3 != 0) {
        viWss0 = 0;
        viWss1 = 0;
        viWss2 = 0;
        viWss3 = 0;
        viEncoderDirtyFlags |= 2;
    }
    __VISetWSS();
    if (viClosedCaption0 != 0 || viClosedCaption1 != 0 || viClosedCaption2 != 0 || viClosedCaption3 != 0) {
        viClosedCaption0 = 0;
        viClosedCaption1 = 0;
        viClosedCaption2 = 0;
        viClosedCaption3 = 0;
        viEncoderDirtyFlags |= 4;
    }
    __VISetClosedCaption();
    VI_SEND_REG_BLOCK(viEncoderBuf);
    if (viEncoderGain != 0) {
        viEncoderGain = 0;
        viEncoderDirtyFlags |= 0x40;
    }
    __VISendEncoderReg0A();
    viWriteReg(3, 1);
    __VISetLinearGamma();
    viEncoderSerial = 0;
}
