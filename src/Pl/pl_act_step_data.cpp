/*
 * Pl/pl_act_step_data.cpp - the data of the player action step band: the step tables, gun/shell/skill tables and the
 *   motion-number rows the act state machine indexes (data-only, no bodies).
 * RANGE. no .text; .data 0x805BDC48-0x805C15A8 (3 `u32` blocks of step tables, 9 pointer tables, 5 sharpness rows, the
 *   motion rows), .bss 0x806AACC0-0x806AB3E0 (ten `s16` rows the motion tables point at).  Its readers are
 *   `Pl/pl_act_step.cpp`'s step band, `Pl/pl_act.cpp`, `lobby/lb_quest_ui.cpp` and `menu/menu_infomation.cpp`;
 *   `Pl/pl_act_step_data.h` declares the words they spell.
 * NAMES. The file name follows the unit that reads it.  GUESS: `pl_steps_stop`, `pl_steps_run_turn` (the acts that hand
 *   them to `Pl_act_set_step_table`), `pl_steps_by_kind`/`pl_steps_slot3_by_kind` (`fn_802771A0`'s per-weapon-kind
 *   picks), `pl_item_icon_kind_tbl`, `pl_shell_*`, `pl_gun_ammo_entry_tbl`, `pl_skill_*`, `pl_sharpness_row_*`,
 *   `pl_motion_*` (the two lookups at 0x8026A00C/0x8026A068 index them) and the foreign
 *   `pl_steps_kind{0,1,2,7}[_slot3]` (named after `pl_steps_kind8`, the ninth entry of the same tables).
 * RESIDUALS. flipcheck: `.data` differs in 73 bytes (23 step-table words) and relocation targets until `config.yml`
 *   blocks the relocations dtk reads into them: the step tables' words that look like code addresses (`0x8016....`,
 *   `0x800103E7`, `0x8001FFEC`) are record data, and `.data` 0x805BDC48-0x805BF448 is byte-coded records (as the weapon-3
 *   tables are); the two `pl_steps_by_kind` words 0x805C9170/0x805C93C4 (weapon kind 1's tables, in the unclaimed
 *   weapon-1 data 0x805C80A8-0x805C9568: request flip-999b#1) are real pointers and are spelled as externs.
 * SHAPES. MWCC aligns every array to 4 and every array whose size is a multiple of 8 to 8, so the map's rows are cut where
 *   an array can sit: `pl_act_step_table_247` (0x14C) and `pl_act_step_table_247_tail` (0xDC) split the 0x228-byte run
 *   at a 4-aligned seam, and `pl_steps_walk` (0x1B4) / `pl_steps_walk_end` (0x1C) split a 0x1D0 table that retail keeps at
 *   4 mod 8; the two tails are `__declspec(export)` (no other unit references them).  `lbl_805C0476` was the second
 *   half of the 84-record `pl_skill_rec_tbl` (the 0xFFFF terminator is its last record).
 */

