/* Loads the arena's `.brres` texture pack into a resource-memory slot and binds its textures (with their
 * palettes) to draw-shape texture slots; on failure it raises the assert and clears slots 7..12. */
#pragma pool_data off
extern "C" void arena_resource_load(void) {
    const char** name;
    ArenaResourceInfo* info = &arena_resource_info;
    char path[128];
    nw4r::g3d::ResFile file;
    u32 tex;
    u32 pltt;
    u32 file_tmp;
    u32 tex_word;
    u32 pltt_word;
    s32 handle;
    void* mem;
    ResEntry* entry;
    u16 i;

    cnvt_eur_fname(path, (char*)info->name_0x04);
    handle = pull_res_mem((char*)info->name_0x04, info->size_0x00, 1);
    if (handle >= 0) {
        mem = getResMemAdrs(handle);
        set_arena_idx(1);
        if (mem != NULL) {
            if (load_file(path, (u32)mem, info->size_0x00) != 0) {
                res_file_ctor((u32*)&file, 0);
                res_tex_ctor(&tex, 0);
                res_pltt_ctor(&pltt, 0);
                nwAddResource((char*)info->name_0x04, mem);
                entry = ckResourceName((char*)info->name_0x04);
                if (entry != NULL) {
                    res_file_assign((u32*)&file, res_file_ctor(&file_tmp, (u32)entry->data));
                    for (i = 0, name = arena_texture_names; i < 31; i++) {
                        tex_word = file.GetResTex(*name);
                        res_tex_assign(&tex, &tex_word);
                        if (res_tex_has_pltt(&tex)) {
                            pltt_word = file.GetResPltt(*name);
                            res_pltt_assign(&pltt, &pltt_word);
                        }
                        draw_shape_tex_slot_set(&tex, &pltt, i, 1);
                        name++;
                    }
                    return;
                }
            }
            push_res_mem(handle);
        }
    }
    nw4r::db::Panic("arenatask.cpp", 260, "NW4R:Failed assertion 0");
    draw_shape_tex_slots_clear(7, 12);
}
#pragma pool_data reset

/* Fills the arena quest-info rows (one per arena quest id 0x2328 + i) from the quest records the game
 * loaded, and picks each row's clear-time limit from the column the Vs mode selects. */
extern "C" void arena_quest_info_build(u8 mode) {
    u8 column = (mode - 1) == 0;
    s32 index;

    for (index = 0; index < 10; index++) {
        QuestRecord* rec = quest_record_find((u16)(index + 0x2328));

        if (rec != NULL) {
            que_info->row_0x00[index].kind_0x00 = rec->category_0x08A - 1;
            que_info->row_0x00[index].rank_0x01 = rec->field_0x08B;
            que_info->row_0x00[index].flag_0x02 = rec->slot_bytes_0x314[0].value;
            que_info->row_0x00[index].record_0x04 = (const u8*)rec;
            que_info->row_0x00[index].sub_0x08 = (const u8*)rec->field_0x02E;
            que_info->row_0x00[index].time_0x10 = rec->field_0x13A;
            que_info->row_0x00[index].clear_limit_0x14[0] = multi_arena_clr_time[index * 2 + column];
        }
    }
}

/* Packs the colour each of the player's six equip pieces allows into the piece's RGB565 word (+0x04). */
extern "C" void arena_equip_color_set(_PLW* plw) {
    _EQUIP* piece;
    s32 i;

    for (i = 0, piece = plw->equipA; i < 6; piece++, i++) {
        if ((u8)equip_kind_table_class(piece->kind) == 0 && EnableChangeColor(piece) == 1) {
            u8 rgb[4];
            s32 rgba = equip_color_rgba_get(equip_color_index_get(piece));

            color_rgba_copy(rgb, (const u8*)&rgba);
            piece->deco_level = (((rgb[0] & 0xF8) << 8) | ((rgb[1] & 0xFC) * 8)) | ((rgb[2] & 0xF8) >> 3);
        }
    }
}

/* Copies the id byte and the u16 that follows it out of one source record into a head. */
extern "C" void arena_eqdata_head_set(ArenaEqDataHead* dst, const u16* src) {
    dst->id_0x00 = (u8)src[0];
    dst->value_0x02 = src[1];
}

/* Records the equip index a remote player picked and marks it dirty; the local player's own choice never
 * comes through here. */
extern "C" void arena_other_player_eq_set(u8 player, u8 equip) {
    ArenaWork* work = &arena_work;
    if (player != (s8)my_player_no()) {
        work->slot_0x14[1].ready_0x0B = 1;
        work->slot_0x14[1].player_0x00 = equip;
    }
}

/* Converts one player's acdata equip record (0xA0 bytes each, in the quest record's acdata block) into
 * the arena's own `_arena_eq_data` view: eight head records, the slot count and the two trailing blobs. */
void dl_acdata_to_ar_eqdata(_arena_eq_data* data, u8 index) {
    QuestRecord* rec = quest_record_get();
    const u16* src = (const u16*)((const u8*)rec + rec->acdata_ofs_0x4B4);

    src += (index * 0xA0) / 2;

    memset(data, 0, sizeof(_arena_eq_data));
    arena_eqdata_head_set(&data->head_0x00[0], src);
    arena_eqdata_head_set(&data->head_0x00[1], src + 2);
    arena_eqdata_head_set(&data->head_0x00[2], src + 4);
    arena_eqdata_head_set(&data->head_0x00[3], src + 6);
    arena_eqdata_head_set(&data->head_0x00[4], src + 8);
    arena_eqdata_head_set(&data->head_0x00[5], src + 10);
    arena_eqdata_head_set(&data->head_0x00[6], src + 12);
    arena_eqdata_head_set(&data->head_0x00[7], src + 14);
    data->count_0x60 = 6;
    memcpy(data->body_0x6C, src + 16, 0x60);
    memcpy(data->tail_0xCC, src + 64, 0x20);
}

/* Builds the arena user-data record from the local player's user block (or the vs user block) and the
 * stage's equip record, then applies it to the player's move work. */
extern "C" void arena_eqdata_from_userdata(_PLW* plw) {
    ArenaWork* work = &arena_work;
    _arena_eq_data eq;
    u8* buf = arena_user_data_buf;
    u8* src;
    s32 i;

    if (work->mode_0x04 == 2) {
        src = (u8*)get_userdata();
        buf[0] = src[0];
        buf[1] = src[1];
        buf[2] = src[159];
        buf[3] = src[2];
        *(u32*)&buf[4] = *(u32*)&src[20];
        buf[8] = src[158];
        buf[9] = src[14752];
        buf[10] = src[14753];
        buf[11] = src[14778];
        *(u32*)&buf[16] = *(u32*)&src[14780];
        buf[12] = src[15846];
        buf[13] = src[15847];

        dl_acdata_to_ar_eqdata(&eq, (u8)(plw->chunk_ofs % 4));
        memcpy(buf + 20, &eq, 236);
        arena_userdata_apply(buf, (u8*)plw);
        arena_equip_color_set(plw);

        /* A byte-wise copy of the seventeen profile bytes the user block carries; it names no field
         * of either record (`_PLW` has no labelled run there), so the offsets are written raw. */
        for (i = 0; i < 17; i++) {
            plw->user_profile_0x5CA[i] = src[3 + i];
        }
    } else {
        if (plw->chunk_ofs <= 3) {
            src = (u8*)get_vsUser_work(0);
        } else {
            src = (u8*)get_vsUser_work(1);
        }

        if (src == NULL) {
            return;
        }

        buf[0] = src[0];
        buf[1] = src[1];
        buf[2] = src[33];
        buf[3] = src[2];
        *(u32*)&buf[4] = *(u32*)&src[20];
        buf[8] = src[32];
        buf[9] = src[34];
        buf[10] = src[35];
        buf[11] = src[36];
        *(u32*)&buf[16] = *(u32*)&src[40];
        buf[12] = src[37];
        buf[13] = src[38];

        buf = arena_user_data_buf;
        memcpy(buf + 20, &work->eq_data_0x10->eq_0x000[plw->chunk_ofs % 4], 236);
        arena_userdata_apply(buf, (u8*)plw);
        arena_equip_color_set(plw);

        for (i = 0; i < 17; i++) {
            plw->user_profile_0x5CA[i] = src[3 + i];
        }
    }
}

/* Builds the same record from the local player's own move work: its profile bytes are mirrored into the
 * buffer and its item slots cleared before the record is applied back. */
extern "C" void arena_eqdata_from_vsuser(_PLW* plw) {
    u8* buf = arena_user_data_buf + ((u32)plw->chunk_ofs << 8);
    s32 i;

    buf[0] = plw->se_name_set;          /* _PLW +0x14  */
    buf[1] = plw->field_0x25C[5];       /* _PLW +0x261 */
    buf[2] = plw->se_name_idx;          /* _PLW +0x1D  */
    buf[3] = plw->field_0x25C[4];       /* _PLW +0x260 */
    *(u32*)&buf[4] = ((u32)plw->field_0x258[0] << 24) | ((u32)plw->field_0x258[1] << 16) |
                     ((u32)plw->field_0x258[2] << 8) | plw->field_0x258[3];   /* _PLW +0x258..0x25B */
    buf[8] = plw->user_profile_0x1C;    /* _PLW +0x1C  */
    buf[9] = plw->user_profile_0xB1C[0];   /* _PLW +0xB1C */
    buf[10] = plw->user_profile_0xB1C[1];  /* _PLW +0xB1D */
    buf[11] = plw->field_0x25C[6];      /* _PLW +0x262 */
    *(u32*)&buf[16] = ((u32)plw->field_0x25C[0] << 24) | ((u32)plw->field_0x25C[1] << 16) |
                      ((u32)plw->field_0x25C[2] << 8) | plw->field_0x25C[3];  /* _PLW +0x25C..0x25F */
    buf[12] = plw->user_profile_0xB1C[2];  /* _PLW +0xB1E */
    buf[13] = plw->user_profile_0xB1C[3];  /* _PLW +0xB1F */

    /* The item slots the record's consumer resets: the 24 live entries of `slot_id` (the target
     * stops before entries 24/25, which only the union's item-scan view reaches) and all eight of
     * `spare_slot_id`.  MWCC unrolls both loops into one `sth` per u16. */
    for (i = 0; i < 24; i++) {
        plw->slot_id[i].item_id = 0;
        plw->slot_id[i].value = 0;
    }
    for (i = 0; i < 8; i++) {
        plw->spare_slot_id[i].item_id = 0;
        plw->spare_slot_id[i].value = 0;
    }

    arena_userdata_apply(buf, (u8*)plw);
    arena_equip_color_set(plw);
}

/* Stores the sub-mode the task compares against 3 before it hands over to `GameModeExec`. */
extern "C" void arena_sub_mode_set(u8 mode) {
    arena_work.sub_mode_0x4E = mode;
}

/* Copies the fourteen record bytes the arena user-data buffer keeps from a player's Vs user block. */
static inline void arena_user_data_fill(u8* buf, const u8* src) {
    buf[0] = src[0];
    buf[1] = src[1];
    buf[2] = src[33];
    buf[3] = src[2];
    *(u32*)&buf[4] = *(u32*)&src[20];
    buf[8] = src[32];
    buf[9] = src[34];
    buf[10] = src[35];
    buf[12] = src[37];
    buf[13] = src[38];
}

/* Enters the arena's Vs mode: publishes the stage as the quest id, copies both players' equip records out
 * of the stage config and their user blocks into the user-data buffer, and starts the Vs game mode. */
static inline void arena_vs_mode_enter(ArenaWork* work) {
    u8* buf;
    s32 i;

    arena_sub_mode_set(0);
    lb_param_w.field_0x00 = work->stage_0x0C + 0x2328;
    buf = arena_user_data_buf;
    memcpy(buf + 0x14, &((const ArenaStageRecord*)arena_stage_config)[work->stage_0x0C].eq_0x000[work->slot_0x14[0].player_0x00], 0xEC);
    memcpy(buf + 0x114, &((const ArenaStageRecord*)arena_stage_config)[work->stage_0x0C].eq_0x000[work->slot_0x14[1].player_0x00], 0xEC);
    for (i = 0; i < 2; buf += 0x100, i++) {
        const u8* src = (const u8*)get_vsUser_work(i);

        if (src != NULL) {
            arena_user_data_fill(buf, src);
        }
    }
    PlayMode_set(2);
    VsGameModeExec();
}

/* The arena task body: step 0 loads the arena and sets its mode up, step 1 runs the match and reacts to
 * its result (a Vs start, a leave to the lobby, a network drop), steps 2-5 unwind to the title. */
extern "C" void arena_task(TaskSlot* task) {
    ArenaWork* work = &arena_work;
    s32 result;

    switch (task->step_0x08) {
    case 0:
        if (file_loading_ck(NULL, NULL) != 1) {
            if (system_w.net_session_0x90f == 0) {
                system_w.vs_mode_0x8b0 = 1;
                if (system_w.online_0x8ae == 1 && work->sub_mode_0x4E == 3) {
                    arena_cfg_apply(0);
                    arena_vs_mode_enter(work);
                    return;
                }
            } else {
                s8 server = (s8)NetCtrlWk::getSelectedServer();
                s8 count;

                if (server < 0) {
                    my_player_no_set(0);
                } else {
                    my_player_no_set(server);
                }
                count = countOccupiedServerSlots();
                if (count <= 0) {
                    player_count_set(1);
                } else {
                    player_count_set(count);
                }
                net_session_close_start();
            }
            arena_result_next(work);
            arena_resource_load();
            if (system_w.online_0x8ae == 1) {
                title_bgm_load();
            }
            task->step_0x08++;
            task->flag_0x14 = 0;
            fade_set(0, 6);
            if (work->mode_0x04 != 2) {
                arena_quest_info_build(work->mode_0x04);
            }
            GameMode_set(3);
            create_move_work(5);
            if (work->mode_0x04 == 1) {
                set_move_work_max(2, 8);
                set_max_player(8);
            } else {
                set_move_work_max(2, 4);
                set_max_player(4);
            }
            set_com_motion_type(3);
            title_se_load();
        }
        break;
    case 1:
        nwMoveStart();
        prim_init_all();
        ai_npc_reaction_forward();
        result = arena_game_task(work);
        if (arena_draw_func[0] != 0) {
            subTransSetPrio(3, arena_draw_func[0], 0, 0);
        }
        if (arena_draw_func[1] != 0) {
            subTransSetPrio(6, arena_draw_func[1], 0, 0);
        }
        nwMoveEnd();
        if (result == 1) {
            system_w.field_0x7ce = 0;
            system_w.field_0x866 = 0;
            all_reset();
            setSoftresetFlag(1);
            clear_FqResult_work();
            clear_qResult_work();
            if (work->mode_0x04 == 2) {
                s32 other = (s8)my_player_no() != 0;
                _arena_eq_data eq;

                dl_acdata_to_ar_eqdata(&eq, work->slot_0x14[other != 0].player_0x00);
                memcpy(arena_user_data_buf + 0x14, &eq, 0xEC);
                dl_acdata_to_ar_eqdata(&eq, work->slot_0x14[(other == 0) & 0xFF].player_0x00);
                memcpy(arena_user_data_buf + 0x114, &eq, 0xEC);
                PlayMode_set(6);
                GameMode_set(1);
                GameModeExec();
            } else {
                arena_vs_mode_enter(work);
            }
        } else if (result == -1) {
            task->step_0x08 = 3;
            bgm_stop_all();
        } else if (result == 2) {
            task->step_0x08 = 2;
        }
        break;
    case 2:
        prim_init_all();
        system_w.field_0x7ce = 1;
        system_w.online_0x8ae = 0;
        game_reset_to_title();
        break;
    case 3:
        if (net_session_close_state_get() != 0) {
            loading_disp_set(0, 0);
            task->step_0x08++;
            task->wait_0x0C = 60;
        }
        break;
    case 4:
        if (system_w.net_result_wait_0x8c1 != 1 || NetCtrlWk::getLobbyReadyByte() == 2) {
            if (arena_draw_func[3] != 0) {
                if (get_network_sub_error_msg() == 0) {
                    task->wait_0x0C = 0;
                    task->step_0x08++;
                    return;
                }
                subTransSetPrio(9, arena_draw_func[3], 0, 0);
            }
            if (task->wait_0x0C > 0) {
                task->wait_0x0C--;
                return;
            }
            if ((Psw[0].button_0x2C0.pressed_0x04 & 0x10) != 0) {
                sysSE_req(0);
                task->wait_0x0C = 20;
                task->step_0x08++;
            }
        }
        break;
    case 5:
        prim_init_all();
        if (arena_draw_func[3] != 0 && get_network_sub_error_msg() != 0) {
            subTransSetPrio(9, arena_draw_func[3], 0, 0);
        }
        if (task->wait_0x0C > 0) {
            task->wait_0x0C--;
            return;
        }
        NetCtrlWk::clearSubError();
        system_w.field_0x7d5 = 1;
        system_w.leave_flag_0x7d6 = 1;
        system_w.leave_state_0x7d8 = 0;
        system_w.net_session_0x90f = 0;
        system_w.field_0x866 = 0;
        system_w.field_0x7ce = 0;
        sound_frame_entry();
        bgm_stop_all();
        all_reset();
        setSoftresetFlag(1);
        clear_FqResult_work();
        clear_qResult_work();
        GameMode_set(2);
        PlayMode_set(4);
        GameModeExec();
        break;
    }
}

/* Places every player's move work at its arena spawn offset, gives it the motion its equip slot's
 * kind selects, and marks the slot whose own player byte agrees with the index. */
extern "C" void arena_player_init(ArenaWork* params) {
    _PLW* plw = (_PLW*)get_move_work_adrs(2);
    s32 i;
    s32 count = (u16)get_move_work_max(2);

    for (i = 0; i < count; i++, plw++) {
        ArenaEqSlot* slot;
        u16 motion;
        s32 kind;

        if (i < 4) {
            slot = &params->slot_0x14[0];
            if (params->mode_0x04 == 1) {
                kind = 1;
                motion = 2185;
            } else {
                kind = 0;
                motion = 0;
            }
        } else {
            slot = &params->slot_0x14[1];
            kind = 2;
            motion = 0xF778;
        }

        plw->motion_pos_0x3C = arena_player_offset_table[kind * 3];
        plw->motion_pos_0x40 = arena_player_offset_table[kind * 3 + 1];
        plw->motion_pos_0x44 = arena_player_offset_table[kind * 3 + 2];
        plw->field_0x058 = (params->round_0x03 << 8) + motion;

        if ((u32)Get_motion_no(plw) < 700) {
            if (plw->se_name_set != 0) {
                Pl_chr_setX(plw, 700, 0, 0);
            } else {
                Pl_chr_setX(plw, 720, 0, 0);
            }
        }

        if (slot->player_0x00 == (i & 3)) {
            plw->field_0x001 = 1;
        } else {
            plw->field_0x001 = 0;
        }
    }

    params->round_0x03++;
}

/* Points the scene's first camera at the arena: position from `arena_camera_vec[0]`, target from
 * `[1]`, a perspective of the arena's own fov and clip range. */
extern "C" void arena_camera_init(ArenaWork* work) {
    nw4r::g3d::Camera::PostureInfo posture;
    nw4r::g3d::Camera camera;
    s32 handle;

    handle = ((nw4r::g3d::ScnRoot*)pRoot)->GetCamera(0);
    word_copy_return_dst(&camera, &handle);
    camera_posture_info_ctor(&posture);
    posture.mType = 2;
    copyVec3((nw4r::math::VEC3*)&posture.mTargetX, &arena_camera_vec[1]);
    posture.mUnk28 = arena_zero_f;
    camera_position_set(&camera, &arena_camera_vec[0]);
    camera.SetPosture(posture);
    camera.SetPerspective(arena_50f, Screen_w.aspect, arena_camera_near_z, arena_camera_far_z);
}

/* Installs the arena scene's ambient colour and one direct light per entry of its four-colour table (the
 * first light twice), each at its `arena_light_vec` position. */
extern "C" void arena_light_init(void) {
    u32* colors;
    u32 color;
    s32 i;

    color = arena_ambient_color;
    set_amblight(0, *(_GXColor*)&color);

    colors = arena_light_colors;
    color = colors[0];
    make_dir_light2(0, &arena_light_vec[0], *(_GXColor*)&color, 0);
    for (i = 0; i < 4; i++) {
        color = colors[i];
        make_dir_light2(i + 5, &arena_light_vec[i], *(_GXColor*)&color, 0);
    }
}

/* Fills one equip slot's `kind` and its initial `state` for the given kind: kind 1 adds the player's
 * equip page count, kind 2 looks at the id of the acdata record the slot's player owns. */
extern "C" void arena_eqdata_apply(ArenaWork* params, ArenaEqSlot* slot, u8 kind, u8 index) {
    slot->kind_0x08 = kind;
    slot->page_0x02 = 0;
    switch (slot->kind_0x08) {
    case 1: {
        _PLW* base;

        slot->page_limit_0x03 = 5;
        base = (_PLW*)get_move_work_adrs(2);
        if (base != NULL) {
            u8 player = slot->player_0x00;

            slot->page_limit_0x03 += equip_list_page_count((EquipListWork*)&base[player + index * 4]);
        }
        break;
    }
    case 2: {
        _arena_eq_data eq;
        const _arena_eq_data* record;

        if (params->mode_0x04 == 2) {
            dl_acdata_to_ar_eqdata(&eq, slot->player_0x00);
            record = &eq;
        } else {
            record = &params->eq_data_0x10->eq_0x000[slot->player_0x00];
        }
        if (record->head_0x00[0].id_0x00 == 0xB) {
            slot->page_limit_0x03 = 4;
        } else {
            slot->page_limit_0x03 = 3;
        }
        break;
    }
    case 3:
        slot->page_limit_0x03 = 4;
        break;
    default:
        slot->page_limit_0x03 = 0;
        break;
    }
}

/* Clears one equip slot and refills its kind and state from the work block's mode. */
extern "C" void arena_eqdata_reset(ArenaWork* params, ArenaEqSlot* slot, u8 index) {
    slot->player_0x00 = 0;
    slot->player_limit_0x01 = 0;
    slot->page_0x02 = 0;
    slot->page_limit_0x03 = 0;
    slot->stage_col_0x04 = 0;
    slot->stage_row_0x05 = 0;
    slot->stage_cols_0x06 = 0;
    slot->stage_rows_0x07 = 0;
    slot->moved_0x12 = 0;
    slot->ready_0x0B = 0;
    if (params->mode_0x04 == 2) {
        slot->kind_limit_0x09 = 3;
    } else {
        slot->kind_limit_0x09 = 4;
    }
    arena_eqdata_apply(params, slot, 0, index);
    slot->kind_open_0x0A = 0;
    slot->arrow_l_timer_0x0E = 0;
    slot->arrow_r_timer_0x10 = 0;
    slot->grid_mode_0x0C = 0;
}

/* Loads one of the arena's three parameter presets: the mode selects how many equip slots exist and
 * which of the two Vs configurations each of them takes. */
extern "C" void arena_eqdata_setup(ArenaWork* params, u8 mode) {
    params->state_0x00 = mode;
    params->phase_0x01 = 0;
    params->step_0x02 = 0;
    params->round_0x03 = 0;
    switch (mode) {
    case 0:
        arena_eqdata_reset(params, &params->slot_0x14[0], 0);
        params->slot_0x14[0].player_limit_0x01 = 3;
        params->slot_0x14[0].mirror_0x0D = get_arena_cfg(0, 7);
        params->slot_0x14[1].mirror_0x0D = get_arena_cfg(1, 7);
        params->blink_0x44 = 0;
        params->blink_0x46 = 0;
        break;
    case 1:
        arena_eqdata_reset(params, &params->slot_0x14[0], 0);
        params->slot_0x14[0].stage_cols_0x06 = 5;
        params->slot_0x14[0].stage_rows_0x07 = 2;
        params->blink_0x44 = 0;
        params->blink_0x46 = 0;
        break;
    case 2:
        arena_eqdata_reset(params, &params->slot_0x14[0], 0);
        params->slot_0x14[0].player_limit_0x01 = 4;
        arena_eqdata_reset(params, &params->slot_0x14[1], 1);
        params->slot_0x14[1].player_limit_0x01 = 4;
        params->blink_0x44 = 0;
        params->blink_0x46 = 0;
        params->select_countdown_0x48 = 0x1518;
        break;
    default:
        break;
    }
}

/* Resets the arena work for the next round and builds its local (one- or two-player) or network setup,
 * then picks the stage's equip data. */
extern "C" void arena_result_next(ArenaWork* work) {
    ArenaEqSlot* slot;
    ArenaEqSlot* slots;
    s32 i;
    s32 count;

    work->state_0x00 = 0;
    work->phase_0x01 = 0;
    work->step_0x02 = 0;
    work->round_0x03 = 0;
    lb_param_w.flag_0x0C[0] = 0;
    lb_param_w.value_0x10[0] = 0;
    lb_param_w.flag_0x0C[1] = 0;
    lb_param_w.value_0x10[1] = 0;
    lb_param_w.flag_0x0C[2] = 0;
    lb_param_w.value_0x10[2] = 0;
    lb_param_w.value_0x16 = 0;
    lb_param_w.value_0x18 = 0;
    lb_param_w.value_0x1A = 0;
    lb_param_w.value_0x1C = 0;
    if (system_w.online_0x8ae == 0) {
        arena_sub_mode_set(0);
        work->solo_0x50 = 1;
    } else {
        work->solo_0x50 = 0;
    }
    if (system_w.net_session_0x90f == 0) {
        if (system_w.field_0x8af == 0) {
            work->mode_0x04 = 0;
            count = 1;
        } else {
            work->mode_0x04 = 1;
            count = 2;
        }
        work->ready_mask_0x08 = 7;
        work->item_mask_0x0A = 0;
        slots = work->slot_0x14;
        for (i = 0, slot = slots; i < count; i++, slot++) {
            const u32* items;
            s32 bit;
            s32 k;

            arena_eqdata_reset(work, slot, i);
            slot->user_0x14 = get_vsUser_work(i);
            slot->mirror_0x0D = get_arena_cfg(i, 7);
            work->ready_mask_0x08 |= slot->user_0x14->ready_mask_0xBC;
            if (work->mode_0x04 == 0) {
                items = slot->user_0x14->slot_a_0x6C;
            } else {
                items = slot->user_0x14->slot_b_0x94;
            }
            bit = 0;
            for (k = 0; k < 10; k++) {
                if (items[k] != 0) {
                    work->item_mask_0x0A |= (u16)(1 << bit);
                }
                bit++;
            }
            if (system_w.vs_player_done_0x89c[i] == 0) {
                system_w.vs_player_pending_0x850[slot->user_0x14->player_0xCF] = 1;
            }
        }
        for (i = 0; i < count; i++) {
            slots[i].user_0x14->ready_mask_0xBC |= work->ready_mask_0x08;
        }
        switch (work->sub_mode_0x4E) {
        case 1:
            arena_eqdata_setup(work, 1);
            work->slot_0x14[0].stage_col_0x04 = work->stage_0x0C % work->slot_0x14[0].stage_cols_0x06;
            work->slot_0x14[0].stage_row_0x05 = work->stage_0x0C / work->slot_0x14[0].stage_cols_0x06;
            break;
        case 2:
            arena_eqdata_setup(work, 1);
            work->eq_data_0x10 = (const ArenaStageRecord*)arena_stage_config + work->stage_0x0C;
            work->phase_0x01 = 0xC8;
            break;
        default:
            arena_eqdata_setup(work, 0);
            break;
        }
        arena_cfg_apply(0);
    } else {
        NetCtrlWk::copyStaging((u8*)quest_init(0)->record_0x03C);
        work->mode_0x04 = 2;
        work->player_count_0x05 = countOccupiedServerSlots();
        for (i = 0; i < work->player_count_0x05; i++) {
            arena_eqdata_reset(work, &work->slot_0x14[i], i);
        }
        arena_eqdata_setup(work, 1);
        work->phase_0x01 = 0xC8;
    }
    if (work->sub_mode_0x4E != 2) {
        work->stage_0x0C = -1;
    }
    memset(arena_user_data_buf, 0, 0x100);
    memset(arena_user_data_buf + 0x100, 0, 0x100);
}

/* Steps the arena's state machine one frame (equip picker, stage picker and start-up, network picker and
 * match); returns 1 when the round ends, 2 to leave and -1 after a network drop. */
extern "C" s32 arena_game_task(ArenaWork* work) {
    const PadButtons* pads[2];
    u16 moved_row;
    u16 moved_col;
    _arena_eq_data eq;
    s32 n;
    s32 ready;
    s32 i;
    ArenaEqSlot* slot;

    if (isServerSelectState() == 1) {
        NetCtrlWk::flushSession();
    }
    n = (work->mode_0x04 == 1) + 1;
    for (i = 0; i < (s16)n; i++) {
        pads[i] = &Psw[i].button_0x2C0;
    }
    ready = 0;
    switch (work->state_0x00) {
    case 0:
        if (work->solo_0x50 == 0) {
            if ((u32)srt_ready_ck(1) != 1) {
                break;
            }
            PlayStream(1, 58);
            work->solo_0x50 = 1;
        }
        slot = work->slot_0x14;
        switch (work->phase_0x01) {
        case 0:
            switch (work->step_0x02) {
            case 0:
                if ((pads[0]->pressed_0x04 & 0x10) != 0) {
                    switch (slot->player_0x00) {
                    case 0:
                        arena_eqdata_setup(work, 1);
                        titleSE_req(9);
                        break;
                    case 1:
                        work->phase_0x01 = 2;
                        for (i = 0; i < (s16)n; i++) {
                            work->slot_0x14[i].page_0x02 = work->slot_0x14[i].mirror_0x0D;
                            work->slot_0x14[i].page_limit_0x03 = 3;
                            work->slot_0x14[i].ready_0x0B = 0;
                        }
                        sysSE_req(5);
                        break;
                    case 2:
                        sysSE_req(0);
                        work->step_0x02++;
                        work->wait_0x06 = 0;
                        PlayStream(1, 1);
                        break;
                    }
                } else {
                    slot->player_0x00 = menu_cursor_step(slot->player_0x00, slot->player_limit_0x01,
                                                         pads[0]->pressed_0x04 | pads[0]->held_0x14, 1, 2);
                }
                break;
            case 1:
                if ((u32)file_loading_ck(NULL, NULL) != 1) {
                    if (++work->wait_0x06 > 16) {
                        return 2;
                    }
                }
                break;
            }
            break;
        case 1:
            if ((pads[0]->pressed_0x04 & 0x10) == 0) {
                if ((pads[0]->pressed_0x04 & 0x20) != 0) {
                    work->phase_0x01 = 0;
                } else {
                    slot->page_0x02 = menu_cursor_step(slot->page_0x02, slot->page_limit_0x03,
                                                       pads[0]->pressed_0x04 | pads[0]->held_0x14, 1, 2);
                }
            }
            break;
        case 2:
            for (i = 0, slot = work->slot_0x14; i < (s16)n; i++) {
                ArenaEqSlot* slot_i = &work->slot_0x14[i];
                const PadButtons* pad;

                slot_i->moved_0x12 = 0;
                pad = pads[i];
                if (slot_i->ready_0x0B == 0) {
                    u16 buttons = pad->pressed_0x04;

                    if ((buttons & 0x10) != 0) {
                        slot_i->ready_0x0B = 1;
                        slot_i->mirror_0x0D = slot_i->page_0x02;
                        sysSE_req(0);
                        arena_cfg_set(i, 7, slot_i->mirror_0x0D);
                    } else if ((buttons & 0x20) != 0) {
                        slot_i->ready_0x0B = 1;
                        sysSE_req(1);
                    } else {
                        slot_i->page_0x02 = menu_cursor_step_forward(slot_i->page_0x02, slot_i->page_limit_0x03,
                                                                      buttons | pad->held_0x14, 4, 8, 6,
                                                                      &slot_i->moved_0x12);
                    }
                }
            }
            for (i = 0; i < (s16)n; i++, slot++) {
                if (slot->ready_0x0B != 0) {
                    ready++;
                }
            }
            if (ready >= (s16)n) {
                work->phase_0x01 = 0;
            }
            break;
        }
        break;
    case 1:
        if (++work->blink_0x44 > 20) {
            work->blink_0x44 = 0;
        }
        switch (work->phase_0x01) {
        case 0:
            if (work->solo_0x50 == 0) {
                if ((u32)srt_ready_ck(1) != 1) {
                    break;
                }
                PlayStream(1, 58);
                work->solo_0x50 = 1;
            }
            switch (work->step_0x02) {
            case 0:
                if ((pads[0]->pressed_0x04 & 0x10) != 0) {
                    s32 stage = work->slot_0x14[0].stage_row_0x05 * work->slot_0x14[0].stage_cols_0x06;

                    stage += work->slot_0x14[0].stage_col_0x04;

                    if ((work->ready_mask_0x08 & (1 << stage)) != 0) {
                        work->step_0x02++;
                        work->stage_0x0C = stage;
                        work->eq_data_0x10 = (const ArenaStageRecord*)arena_stage_config + stage;
                        work->wait_0x06 = 0;
                        titleSE_req(11);
                        PlayStream(1, 1);
                    } else {
                        sysSE_req(2);
                    }
                } else if ((pads[0]->pressed_0x04 & 0x20) != 0) {
                    arena_eqdata_setup(work, 0);
                    sysSE_req(1);
                } else {
                    work->slot_0x14[0].stage_col_0x04 = menu_cursor_step_fixed_tail(
                        work->slot_0x14[0].stage_col_0x04, work->slot_0x14[0].stage_cols_0x06,
                        pads[0]->pressed_0x04 | pads[0]->held_0x14, 4, 8, &moved_col);
                    work->slot_0x14[0].stage_row_0x05 = menu_cursor_step_fixed_tail(
                        work->slot_0x14[0].stage_row_0x05, work->slot_0x14[0].stage_rows_0x07,
                        pads[0]->pressed_0x04 | pads[0]->held_0x14, 1, 2, &moved_row);
                    if (moved_col != 0 || moved_row != 0) {
                        titleSE_req(10);
                    }
                }
                break;
            case 1:
                if (++work->wait_0x06 > 16) {
                    work->step_0x02++;
                    if (system_w.field_0x8af == 0) {
                        loading_disp_set(1, 0);
                    } else {
                        loading_disp_set(1, 5);
                    }
                    snd_bank_layout(0);
                    scene_se_bank_load(0, 0);
                    title_bgm_load();
                }
                break;
            case 2:
                if (srt_ready_ck(1) != 0) {
                    work->phase_0x01++;
                    init_player_work();
                    player_init_data_load();
                    player_control_move();
                }
                break;
            }
            break;
        case 1:
            if ((u32)file_loading_ck(NULL, NULL) != 1) {
                work->phase_0x01++;
                arena_camera_init(work);
                pl_motion_set();
                ((StageMapView*)stage_w)->mapno = 0xFF;
                ((StageMapView*)stage_w)->areano = 0;
                filter_reset();
                light_init();
                arena_light_init();
                player_control_move();
            }
            break;
        case 2:
            if (player_move_start_ck() == 1) {
                title_se_load();
                player_move_start(-1);
                if (work->mode_0x04 == 2) {
                    work->phase_0x01++;
                    work->sync_sent_0x4A = 0;
                    work->sync_tick_0x4C = 0;
                } else {
                    loading_disp_set(0, 0);
                    PlayStream(1, 55);
                    arena_eqdata_setup(work, 2);
                }
            }
            player_control_move();
            break;
        case 3:
            if (getLinkStatus() == 1 || system_w.net_result_wait_0x8c1 == 1) {
                net_session_abort_start();
                return -1;
            }
            if (isSessionStartDone() != 0) {
                if (isReadyCountOne() == 1 && work->sync_sent_0x4A == 0 && (u32)lb_seen_pad_ck(4) == 1) {
                    work->sync_sent_0x4A = 1;
                    lb_sub0b_send(NetCtrlWk::getSelectedServer(), 4);
                }
                if ((++work->sync_tick_0x4C & 0x1F) == 0) {
                    lb_sub0a_send(NetCtrlWk::getSelectedServer(), 4);
                }
                if (lb_handled_ck(4) != 0) {
                    loading_disp_set(0, 0);
                    PlayStream(1, 55);
                    arena_eqdata_setup(work, 2);
                }
            }
            break;
        case 200:
            work->phase_0x01++;
            if (work->mode_0x04 == 2 || system_w.field_0x8af == 0) {
                loading_disp_set(1, 0);
            } else {
                loading_disp_set(1, 5);
            }
            snd_bank_layout(0);
            scene_se_bank_load(0, 0);
            title_bgm_load();
            break;
        case 201:
            if (srt_ready_ck(1) != 0) {
                work->phase_0x01 = 1;
                init_player_work();
                player_init_data_load();
                player_control_move();
            }
            break;
        }
        break;
    case 2:
        if (work->mode_0x04 == 2 && getLinkStatus() == 1) {
            net_session_abort_start();
            return -1;
        }
        if (++work->blink_0x44 > 35) {
            work->blink_0x44 = 0;
        }
        if (++work->blink_0x46 > 40) {
            work->blink_0x46 = 0;
        }
        if (work->select_countdown_0x48 > 0) {
            work->select_countdown_0x48--;
        }
        switch (work->phase_0x01) {
        case 0:
            for (i = 0; i < (s16)n; i++) {
                ArenaEqSlot* slot_i = &work->slot_0x14[i];
                const PadButtons* pad;

                slot_i->moved_0x12 = 0;
                pad = pads[i];
                if (slot_i->arrow_l_timer_0x0E != 0) {
                    if (++slot_i->arrow_l_timer_0x0E > 10) {
                        slot_i->arrow_l_timer_0x0E = 0;
                    }
                }
                if (slot_i->arrow_r_timer_0x10 != 0) {
                    if (++slot_i->arrow_r_timer_0x10 > 10) {
                        slot_i->arrow_r_timer_0x10 = 0;
                    }
                }
                if (slot_i->ready_0x0B == 0) {
                    if (slot_i->kind_open_0x0A == 0) {
                        if ((pad->hold_0x00 & 0x80) != 0 && slot_i->grid_mode_0x0C == 0 &&
                            (work->mode_0x04 != 2 || work->select_countdown_0x48 != 0)) {
                            slot_i->kind_open_0x0A = 1;
                            sysSE_req(5);
                        } else {
                            u32 buttons = pad->pressed_0x04;

                            if ((buttons & 0x10) != 0 || (work->mode_0x04 == 2 && work->select_countdown_0x48 == 0)) {
                                if (slot_i->grid_mode_0x0C == 0) {
                                    slot_i->ready_0x0B = 1;
                                    sysSE_req(0);
                                    if (work->mode_0x04 == 2) {
                                        work->phase_0x01 = 100;
                                        lb_sub1d_send(my_player_no(), slot_i->player_0x00);
                                    }
                                }
                            } else if (work->mode_0x04 != 2 && (buttons & 0x2000) != 0) {
                                slot_i->grid_mode_0x0C ^= 1;
                                slot_i->stage_col_0x04 = 0;
                                slot_i->stage_row_0x05 = 0;
                                slot_i->stage_cols_0x06 = 4;
                                slot_i->stage_rows_0x07 = 4;
                                sysSE_req(5);
                            } else if (slot_i->grid_mode_0x0C == 0) {
                                if ((u32)(slot_i->kind_0x08 - 1) > 2) {
                                    if (slot_i->kind_0x08 == 0) {
                                        slot_i->player_0x00 = menu_cursor_step_forward(
                                            slot_i->player_0x00, slot_i->player_limit_0x01, buttons | pad->held_0x14,
                                            4, 8, 6, &slot_i->moved_0x12);
                                        if ((slot_i->moved_0x12 & 4) != 0) {
                                            slot_i->arrow_l_timer_0x0E = 1;
                                        } else if ((slot_i->moved_0x12 & 8) != 0) {
                                            slot_i->arrow_r_timer_0x10 = 1;
                                        }
                                    }
                                } else {
                                    buttons |= pad->held_0x14;
                                    if ((buttons & 0xC) != 0) {
                                        slot_i->player_0x00 = menu_cursor_step(
                                            slot_i->player_0x00, slot_i->player_limit_0x01, buttons, 4, 8);
                                        switch (slot_i->kind_0x08) {
                                        case 2: {
                                            const _arena_eq_data* record;

                                            if (work->mode_0x04 == 2) {
                                                dl_acdata_to_ar_eqdata(&eq, slot_i->player_0x00);
                                                record = &eq;
                                            } else {
                                                record = &work->eq_data_0x10->eq_0x000[slot_i->player_0x00];
                                            }
                                            if (record->head_0x00[0].id_0x00 == 0xB) {
                                                slot_i->page_limit_0x03 = 4;
                                            } else {
                                                slot_i->page_limit_0x03 = 3;
                                            }
                                            break;
                                        }
                                        case 1: {
                                            _PLW* base;

                                            slot_i->page_limit_0x03 = 5;
                                            base = (_PLW*)get_move_work_adrs(2);
                                            if (base != NULL) {
                                                slot_i->page_limit_0x03 += equip_list_page_count(
                                                    (EquipListWork*)&base[slot_i->player_0x00 + i * 4]);
                                            }
                                            break;
                                        }
                                        }
                                        if (slot_i->page_0x02 >= slot_i->page_limit_0x03) {
                                            slot_i->page_0x02 = 0;
                                        }
                                    } else {
                                        slot_i->page_0x02 = menu_cursor_step_fixed_tail(
                                            slot_i->page_0x02, slot_i->page_limit_0x03, pad->trigger_0x0C, 0x800,
                                            0x400, &slot_i->moved_0x12);
                                    }
                                }
                            } else {
                                slot_i->stage_col_0x04 = menu_cursor_step(
                                    slot_i->stage_col_0x04, slot_i->stage_cols_0x06, buttons | pad->held_0x14, 4, 8);
                                slot_i->stage_row_0x05 = menu_cursor_step(
                                    slot_i->stage_row_0x05, slot_i->stage_rows_0x07,
                                    pad->pressed_0x04 | pad->held_0x14, 1, 2);
                            }
                        }
                    } else if ((pad->hold_0x00 & 0x80) != 0 &&
                               (work->mode_0x04 != 2 || work->select_countdown_0x48 != 0)) {
                        slot_i->kind_open_0x0A = 1;
                        slot_i->kind_0x08 = menu_cursor_step_fixed_tail(
                            slot_i->kind_0x08, slot_i->kind_limit_0x09, pad->pressed_0x04 | pad->held_0x14, 1, 2,
                            &slot_i->moved_0x12);
                        if ((slot_i->moved_0x12 & 3) != 0) {
                            arena_eqdata_apply(work, slot_i, slot_i->kind_0x08, i);
                        }
                    } else {
                        slot_i->kind_open_0x0A = 0;
                    }
                } else if (slot_i->ready_0x0B == 1) {
                    ready++;
                    if (system_w.field_0x8af == 0) {
                        work->phase_0x01++;
                        work->wait_0x06 = 0;
                        sysSE_stop(31);
                        PlayStream(1, 1);
                    } else if (ready == 2) {
                        work->phase_0x01++;
                        work->wait_0x06 = 0;
                        sysSE_stop(31);
                        PlayStream(1, 1);
                    } else if ((pad->pressed_0x04 & 0x20) != 0) {
                        slot_i->ready_0x0B = 0;
                        ready--;
                    }
                }
            }
            break;
        case 1:
            if (++work->wait_0x06 > 16) {
                return 1;
            }
            break;
        case 100:
            if (countOccupiedServerSlots() <= 1 || work->slot_0x14[1].ready_0x0B == 1) {
                work->phase_0x01 = 1;
                work->wait_0x06 = 0;
                sysSE_stop(31);
                PlayStream(1, 1);
            }
            break;
        }
        arena_player_init(work);
        player_control_move();
        yure_move();
        light_move();
        ((nw4r::g3d::ScnRoot*)pRoot)->SetCurrentCamera(0);
        break;
    }
    return 0;
}

