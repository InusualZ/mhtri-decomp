/* The arc tangent of a ratio in [0, 1], in index units. */
static inline f32 AtanFIdx_(f32 x) {
    u16 idx;
    f32 fidx;
    f32 r;

    x *= 32.0f;
    OSf32tou16(&x, &idx);
    OSu16tof32(&idx, &fidx);
    r = x - fidx;
    return sArcTanTbl[idx].atan_val + r * sArcTanTbl[idx].atan_delta;
}

/* 0x80500E34 (0x68): the sine of an angle index (256 steps per circle). */
f32 SinFIdx(f32 fidx) {
    f32 abs_fidx = FAbs(fidx);
    u16 idx;
    f32 r;
    f32 val;

    while (abs_fidx > 65536.0f) {
        abs_fidx -= 65536.0f;
    }

    idx = F32ToU16(abs_fidx);
    r = abs_fidx - U16ToF32(idx);
    idx &= 0xFF;
    val = sSinCosTbl[idx].sin_val + r * sSinCosTbl[idx].sin_delta;
    return (fidx < 0.0f) ? -val : val;
}

/* 0x80500E9C (0x58): the cosine of an angle index (256 steps per circle). */
f32 CosFIdx(f32 fidx) {
    f32 abs_fidx = FAbs(fidx);
    u16 idx;
    f32 r;

    while (abs_fidx > 65536.0f) {
        abs_fidx -= 65536.0f;
    }

    idx = F32ToU16(abs_fidx);
    r = abs_fidx - U16ToF32(idx);
    idx &= 0xFF;
    return sSinCosTbl[idx].cos_val + r * sSinCosTbl[idx].cos_delta;
}

