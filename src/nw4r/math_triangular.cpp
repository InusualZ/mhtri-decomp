/* 0x80500F60 (0x1A8): the angle of (x, y) in index units, -128..128, by octant reduction. */
f32 Atan2FIdx(f32 y, f32 x) {
    f32 a;
    f32 b;
    f32 c;
    bool minus;

    if (x == 0.0f && y == 0.0f) {
        return 0.0f;
    }

    c = 0.0f;
    if (x >= 0.0f) {
        if (y >= 0.0f) {
            if (x >= y) {
                a = x;
                b = y;
                minus = false;
            } else {
                a = y;
                b = x;
                c = 64.0f;
                minus = true;
            }
        } else {
            y = -y;
            if (x >= y) {
                a = x;
                b = y;
                minus = true;
            } else {
                a = y;
                b = x;
                c = -64.0f;
                minus = false;
            }
        }
    } else {
        if (y >= 0.0f) {
            if (-x >= y) {
                a = -x;
                b = y;
                c = 128.0f;
                minus = true;
            } else {
                a = y;
                b = -x;
                c = 64.0f;
                minus = false;
            }
        } else {
            if (-x >= -y) {
                a = -x;
                b = -y;
                c = -128.0f;
                minus = false;
            } else {
                a = -y;
                b = -x;
                c = -64.0f;
                minus = true;
            }
        }
    }

    if (minus) {
        return c - AtanFIdx_(b / a);
    } else {
        return c + AtanFIdx_(b / a);
    }
}

/* 0x80501108 (0x1BC): the angle of (x, y) as a 16-bit index, 0..65535 per circle. */
u16 Atan2Idx(f32 y, f32 x) {
    f32 a;
    f32 b;
    f32 c;
    bool minus;

    if (x == 0.0f && y == 0.0f) {
        return 0;
    }

    c = 0.0f;
    if (x >= 0.0f) {
        if (y >= 0.0f) {
            if (x >= y) {
                a = x;
                b = y;
                minus = false;
            } else {
                a = y;
                b = x;
                c = 64.0f;
                minus = true;
            }
        } else {
            y = -y;
            if (x >= y) {
                a = x;
                b = y;
                c = 256.0f;
                minus = true;
            } else {
                a = y;
                b = x;
                c = 192.0f;
                minus = false;
            }
        }
    } else {
        if (y >= 0.0f) {
            if (-x >= y) {
                a = -x;
                b = y;
                c = 128.0f;
                minus = true;
            } else {
                a = y;
                b = -x;
                c = 64.0f;
                minus = false;
            }
        } else {
            if (-x >= -y) {
                a = -x;
                b = -y;
                c = 128.0f;
                minus = false;
            } else {
                a = -y;
                b = -x;
                c = 192.0f;
                minus = true;
            }
        }
    }

    return F32ToU16(256.0f * (minus ? c - AtanFIdx_(b / a) : c + AtanFIdx_(b / a)));
}

