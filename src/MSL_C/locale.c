/*
 * MSL_C/locale.c - the C locale (data only): the narrow ctype class/case tables, the `_lconv` numeric record, the
 *    per-category records ("C" collate, ctype, monetary, numeric, time) and the `_current_locale` record that links them.
 *
 * RANGE. .rodata 0x80572620..0x80572B28; .data 0x8060EC00..0x8060EDF8; .sdata2 0x8079C9E0..0x8079C9F8.
 * FLAGS. `mw_version` GC/2.7 with `-str reuse,nopool,readonly`: the target keeps each string literal as its own object
 *    (`.sdata2` for the 1..6 byte ones, `.rodata` 4-aligned for the rest), which Wii/1.3 cannot express because its
 *    `readonly` always pools the strings into one `@stringBase0`; GC/2.7 (and 1.3.2..2.6) lays them out as the target.
 * NAMES. file name GUESS (MSL `locale.c`); `_lconv` (0x8060EC00) and `_current_locale` (0x8060EDB0) are the map's names;
 *    `ctype_class_map`, `ctype_lower_map`, `ctype_upper_map` (0x80572620 / 0x80572820 / 0x80572920), `c_locale_ctype`,
 *    `collate_weights`, `c_locale_collate`, `c_locale_monetary`, `c_locale_numeric` and `c_locale_time` are GUESSes named
 *    from the record slots that reference them; the `CollateLocale` field names `first_char` / `last_weight` are GUESSes
 *    (0x20 and 0x6E; the weights table has 96 entries).
 * EVIDENCE. `.data` records read in order: `_lconv`, the ctype descriptor (points at the three narrow and three wide
 *    tables and the two no-conversion multibyte routines), the 96-entry weights table, then the collate, monetary,
 *    numeric and time records, then `_current_locale` (+0x34 collate, +0x38 ctype, +0x3C monetary, +0x40 numeric,
 *    +0x44 time). The strings are plain literals: `.sdata2` holds `.`, empty, `AM|PM`, `%T`; `.rodata` holds the format and
 *    name strings.
 * RESIDUALS. none known; `.rodata` ends 2 B and `.sdata2` 5 B short of the claim (alignment fill, flipcheck READY).
 * SHAPES. every record is a plain initialised global in definition order; the one function-pointer cast adapts the
 *    multibyte routines to `CtypeTables`.
 */
