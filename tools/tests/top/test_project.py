"""tools/project.py's compile edge: the post-steps (objalign, objextab) read the unit's `splits.txt` claim and the
target object `dol split` wrote, so the edge names the target object as an implicit input - a seam that moves a unit's
range rewrites its target object, and the candidate is recompiled (and renamed) with it - and objextab's unwind rule
(`tools/lib/binary/extab.py`) beside objextab itself."""
import sys, pathlib; sys.path.insert(0, str(next(p for p in pathlib.Path(__file__).resolve().parents if (p / "tools" / "__init__.py").is_file())))

import json
import os
import subprocess
from pathlib import Path

from tools.lib import testing

TIER = "fixture"


#: Run in a child whose working directory is the fixture: `generate_build_ninja` resolves every path (and writes
#: `build.ninja`) against the current directory, and a fixture-tier test may not change into the live tree again.
GENERATE = """
import json, sys
from pathlib import Path
sys.path.insert(0, sys.argv[1])
from tools import project
config = project.ProjectConfig()
config.version, config.linker_version, config.ldflags = "RMHE08", "Wii/1.1", []
config.check_sha_path = Path("config/RMHE08/build.sha1")
config.config_path = Path("config/RMHE08/config.yml")
config.dtk_tag = config.compilers_tag = config.binutils_tag = config.sjiswrap_tag = config.objdiff_tag = "v1.0.0"
config.progress = False
config.libs = [{"lib": "ef", "mw_version": "Wii/1.3", "cflags": [], "progress_category": None,
                "objects": [project.Object(False, "ef/a.cpp")]}]
build_config = {"version": "1.0.0", "name": "main", "module_id": 0, "ldscript": "build/RMHE08/ldscript.lcf",
                "entry": "__start", "modules": [], "links": [],
                "units": [{"object": json.loads(sys.argv[2]), "name": "ef/a.cpp", "autogenerated": False}]}
project.generate_build_ninja(config, config.objects(), build_config)
"""


def compile_edge(t, unit_object: str | None) -> str:
    """Generate `build.ninja` for one registered C++ unit in fixture `t`; the unit's compile edge, continuation lines
    joined. `unit_object` is the target object `config.json` names for the unit (None: dtk wrote none)."""
    t.write("src/ef/a.cpp", "int x;\n")
    live = str(next(p for p in Path(__file__).resolve().parents if (p / "tools" / "__init__.py").is_file()))
    subprocess.run([sys.executable, "-c", GENERATE, live, json.dumps(unit_object)], cwd=str(t.root), check=True,
                   capture_output=True)
    text = t.read("build.ninja")
    edges = [line for line in text.replace("$\n", "").splitlines()
             if line.startswith("build ") and ": mwcc" in line and "a.o" in line.split(":")[0]]
    return edges[0] if edges else ""


def test_target_object_is_an_input(c):
    """Mutation: before, the edge's implicit inputs stopped at `tools\\elf\\objextab.py`, so a `splits.txt` edit left a
    built object with the old `@etb_`/`@eti_` names until something else recompiled it."""
    target = os.path.join("build", "RMHE08", "obj", "ef", "a.o")
    with testing.FixtureTree() as t:
        edge = compile_edge(t, "build/RMHE08/obj/ef/a.o")
    implicit = edge.split("|")[1].split() if "|" in edge else []
    c.check("the unit's target object is an implicit input of its compile edge", target in implicit, True)
    c.check("... and so is objextab's unwind rule", os.path.join("tools", "lib", "binary", "extab.py") in implicit,
            True)
    with testing.FixtureTree() as t:
        edge = compile_edge(t, None)
    c.check("a unit dtk wrote no object for gets no such input",
            any(os.sep + "obj" + os.sep in tok for tok in edge.split()), False)


if __name__ == "__main__":
    raise SystemExit(testing.run(globals()))
